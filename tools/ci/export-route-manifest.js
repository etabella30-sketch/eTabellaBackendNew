#!/usr/bin/env node
/**
 * export-route-manifest: write ROUTE_MANIFEST (libs/api-contracts/src/route-manifest.ts) into the Angular repo as a
 * typed TypeScript module, src/app/features/edge/api/rt-route-manifest.ts: every /realtimeapi and /coreapi route the
 * venue box knows, as a `table` row it answers or a `use_cloud` row it refuses on purpose. Phase 3 of the
 * shared-libraries plan (2026-10-06).
 *
 *   node tools/ci/export-route-manifest.js                    writes ../eTabella angular 21/src/app/features/edge/api/rt-route-manifest.ts
 *   node tools/ci/export-route-manifest.js --fe <repo>        another Angular checkout
 *   node tools/ci/export-route-manifest.js --check            exit 1 when the FE copy differs (nothing written)
 *   node tools/ci/export-route-manifest.js --stdout           print the module
 *
 * A TypeScript module, not JSON: the FE spec imports it without Node APIs or resolveJsonModule, and FE code may read
 * it later. The output is deterministic (no date, no commit): a re-run on an unchanged manifest changes nothing, so
 * the FE file only ever changes with the manifest. Bodies and notes stay out; the fields the FE and the box agree on
 * are in. The check that every call of the four RT services is a row here runs in tools/ci/guards/route-manifest.spec.ts
 * (the FE unit-test bundle has no file system). The manifest is TypeScript, loaded here through ts-node.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { parseArgs, UsageError } = require('./release-edge/args');

const REPO = path.resolve(__dirname, '..', '..');
const MANIFEST_TS = path.join(REPO, 'libs', 'api-contracts', 'src', 'route-manifest.ts');
const FE_FILE = ['src', 'app', 'features', 'edge', 'api', 'rt-route-manifest.ts'];
const DEFAULT_FE = path.resolve(REPO, '..', 'eTabella angular 21');
const SCHEMA = 1;
const FIELDS = ['id', 'family', 'method', 'path', 'liveOwner', 'livePath', 'boxOwner', 'boxKind', 'cloudPath', 'teamScoped', 'identity', 'targetFields'];

/** The exported rows: the FE-relevant fields of every manifest row, in manifest order. */
function manifestRows(rows) {
  return rows.map((row) => {
    const out = {};
    for (const key of FIELDS) if (row[key] !== undefined) out[key] = row[key];
    return out;
  });
}

/** The TypeScript module text for a manifest. */
function render(rows) {
  const literal = JSON.stringify(manifestRows(rows), null, 2).replace(/^/gm, '  ').trimStart();
  return [
    '// GENERATED by etabella_backend-tech tools/ci/export-route-manifest.js from libs/api-contracts/src/route-manifest.ts.',
    '// Do not edit: change the backend manifest and re-run the export. Checked current by the backend guard',
    '// tools/ci/guards/route-manifest.spec.ts, which also checks that every call of the four RT services is a row here.',
    '/* eslint-disable */',
    '',
    '/** One /realtimeapi or /coreapi route as the venue box knows it: answered (`table`) or refused on purpose (`use_cloud`). */',
    'export interface RtRouteManifestRow {',
    '  readonly id: string;',
    "  readonly family: 'authapi' | 'coreapi' | 'realtimeapi' | 'edge';",
    "  readonly method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';",
    '  /** The path as the FE calls it, with the family prefix. */',
    '  readonly path: string;',
    "  readonly liveOwner: 'authapi' | 'coreapi' | 'realtime-server' | 'none';",
    '  readonly livePath: string;',
    "  readonly boxOwner: 'edge' | 'table' | 'controller' | 'use_cloud';",
    "  readonly boxKind?: 'local' | 'local-or-cloud' | 'cloud-read' | 'cloud-write';",
    '  readonly cloudPath?: string;',
    '  readonly teamScoped: boolean;',
    "  readonly identity: 'actor' | 'actor+target';",
    '  readonly targetFields?: readonly string[];',
    '}',
    '',
    'export const RT_ROUTE_MANIFEST_SCHEMA = ' + SCHEMA + ';',
    '',
    'export const RT_ROUTE_MANIFEST: readonly RtRouteManifestRow[] = Object.freeze(' + literal + ');',
    '',
  ].join('\n');
}

/** Loads the TypeScript manifest in this process (ts-node, transpile only). */
function loadManifest() {
  require('ts-node').register({ transpileOnly: true, compilerOptions: { module: 'commonjs' } });
  return require(MANIFEST_TS).ROUTE_MANIFEST;
}

function main(argv) {
  let opts;
  try {
    opts = parseArgs(argv, { '--fe': 'value', '--check': 'flag', '--stdout': 'flag', '--help': 'flag' });
  } catch (err) {
    if (!(err instanceof UsageError)) throw err;
    console.error('export-route-manifest: ' + err.message);
    return 2;
  }
  if (opts.help) {
    console.log('Usage: node tools/ci/export-route-manifest.js [--fe <angular repo>] [--check] [--stdout]');
    return 0;
  }
  const text = render(loadManifest());
  if (opts.stdout) {
    process.stdout.write(text);
    return 0;
  }
  const feRoot = opts.fe ? path.resolve(opts.fe) : DEFAULT_FE;
  const target = path.join(feRoot, ...FE_FILE);
  if (!fs.existsSync(path.dirname(target))) {
    console.error('export-route-manifest: ' + path.dirname(target) + ' does not exist (pass --fe <angular repo>)');
    return 2;
  }
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
  if (opts.check) {
    if (current === text) {
      console.log('export-route-manifest: the FE copy is current (' + target + ')');
      return 0;
    }
    console.error('export-route-manifest: the FE copy differs from the manifest; run the export and commit ' + target);
    return 1;
  }
  if (current === text) {
    console.log('export-route-manifest: unchanged ' + target);
    return 0;
  }
  fs.writeFileSync(target, text);
  console.log('export-route-manifest: wrote ' + target);
  return 0;
}

module.exports = { manifestRows, render, FIELDS, FE_FILE, SCHEMA };

if (require.main === module) process.exitCode = main(process.argv.slice(2));
